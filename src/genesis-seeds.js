export function withGenesisStudy(catalog) {
  return catalog.map(book => book.id !== 'gen' ? book : { ...book,
    messages: book.messages.flatMap(message => message.number === 25 ? [message, studyMessage, seedInventoryMessage] : [message]),
  });
}

const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const numerals = ['一', '二', '三', '四', '五', '六', '七', '八'];

export async function renderGenesisStudy(lookup = lookupVerses) {
  const results = await Promise.allSettled(chapters.map(async chapter => lookup({ book: 'Genesis', chapter: chapter.chapter, startVerse: 1, endVerse: chapter.count })));
  const missingChapters = [];
  let html = `<div class="msg-title">${studyMessage.title}</div><article>`;
  html += '<h2>整理说明</h2><p>本页是依据《创世记生命读经》第1～25篇所作的专题归纳，不是生命读经原文，也不是原作者列出的固定种子清单。按创世记一至四章的顺序整理30个主题，并连同上下文完整列出这四章共106节经文，避免割裂经文。主题名称和总结为本网站整理；所列的发展经文是延伸参读，不与创世记原文混排。</p>';
  html += '<p>经文来源：圣经恢复本简体版，在线载入。下文“生命读经总结”是对相关篇目解释立场的转述；预表、属灵应用与经文的字面记载应当加以区别。经文来源暂时不可用时，会明确标出缺失，不以整理者的话代替经文。</p>';
  for (const [index, chapter] of chapters.entries()) {
    const result = results[index];
    const verses = result.status === 'fulfilled' ? result.value.verses : [];
    const complete = Array.isArray(verses) && verses.length === chapter.count && verses.every((verse, i) => verse.number === i + 1 && typeof verse.text === 'string' && verse.text.trim());
    if (!complete) missingChapters.push(chapter.chapter);
    html += `<h2>${chapter.title}</h2>`;
    for (const [topicIndex, [title, start, end, studies, summary, development]] of chapter.topics.entries()) {
      const reference = `创${numerals[chapter.chapter - 1]}${start}${start === end ? '' : `～${end}`}`;
      html += `<h3>（${numerals[topicIndex]}）${escape(title)}</h3><p><strong>经文：</strong>${reference}</p><blockquote>`;
      html += complete ? verses.filter(verse => verse.number >= start && verse.number <= end).map(verse => `<p><strong>${chapter.chapter}:${verse.number}</strong> ${escape(verse.text)}</p>`).join('')
        : '<p>本章经文暂时未能完整载入。请点击经文出处查看，或点击“重新载入经文”重试；以下总结仍可阅读。</p>';
      html += `</blockquote><p><strong>生命读经总结：</strong>${escape(summary)}</p>`;
      html += `<p><strong>相关篇目：</strong>${studies.map(number => `<a href="/?book=gen&amp;message=${number}">第${number}篇</a>`).join('、')}</p>`;
      html += `<p><strong>发展与参读：</strong>${escape(development)}</p>`;
    }
  }
  html += '<h2>总览：从种子到完成</h2><p>按第1～25篇的解释路线，一至二章着重神的目的与达成目的的生命手续，三章显出堕落以及神所应许、预备的救恩，四章把两个源头发展成两种生活与敬拜的路线。光、形像、管治、生命树、生命河和配偶等主题，在该书的解释中发展至圣经末了的圣城；女人的后裔、神的遮盖、凭信亲近神和呼求主名，则显出神在人堕落后仍把人带回生命的路。</p>';
  html += '<h2>参考篇目：第1～25篇</h2><p>以下链接回到本网站对应的原篇阅读页，可继续点击“阅读原文”核对来源。本页保留原第26篇及以后各篇的编号。</p><ul>';
  html += Array.from({ length: 25 }, (_, index) => `<li><a href="/?book=gen&amp;message=${index + 1}">第${index + 1}篇</a></li>`).join('');
  html += '</ul></article>';
  return { html, kind: 'study', source: studyMessage.source, missingChapters };
}
